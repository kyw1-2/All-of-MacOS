import AppKit
import Combine
import Foundation

/// Local clipboard history. The pasteboard is sampled only after its change
/// counter advances; persistence and hashing never run on the gesture loop.
@MainActor
final class ClipboardStore: ObservableObject {
    struct Settings: Codable, Equatable {
        var enabled = true
        var pasteDirectly = true
        var plainText = false
        var retentionDays = 30
        var ignoredApps: [String] = ["com.1password.1password", "com.agilebits.onepassword7",
                                     "com.bitwarden.desktop", "com.apple.keychainaccess"]
        var maxEntries = 1_000
        var maxBytes = 200 * 1_024 * 1_024

        var bounded: Settings {
            var result = self
            // Zero means "Indefinitely" in the settings picker.
            result.retentionDays = min(365, max(0, retentionDays))
            result.maxEntries = min(10_000, max(1, maxEntries))
            result.maxBytes = min(200 * 1_024 * 1_024, max(1_024, maxBytes))
            result.ignoredApps = Array(Set(ignoredApps.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
                .filter { !$0.isEmpty })).sorted()
            return result
        }
    }

    enum StoreError: LocalizedError {
        case emptySelection, cannotWrite, tooLarge, storageUnavailable, invalidArchive
        var errorDescription: String? {
            switch self {
            case .emptySelection: return "The selected clipboard items are no longer available."
            case .cannotWrite: return "The clipboard could not be updated. Try again."
            case .tooLarge: return "This clipboard item exceeds the 20 MB limit."
            case .storageUnavailable: return "Clipboard history could not be saved. Check its storage folder."
            case .invalidArchive: return "Clipboard history could not be read. The original file was preserved."
            }
        }
    }

    static let shared = ClipboardStore()
    static let maximumEntryBytes = 20 * 1_024 * 1_024
    private static let settingsKey = "AOMClipboardSettings.v1"
    private static let excludedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"
    ]
    private static let supportedTypes: Set<String> = [
        NSPasteboard.PasteboardType.string.rawValue, NSPasteboard.PasteboardType.rtf.rawValue,
        NSPasteboard.PasteboardType.rtfd.rawValue, NSPasteboard.PasteboardType.html.rawValue,
        NSPasteboard.PasteboardType.URL.rawValue, NSPasteboard.PasteboardType.fileURL.rawValue,
        NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue,
        "public.jpeg", "public.heic", "public.utf16-external-plain-text", "com.apple.cocoa.pasteboard.color"
    ]

    @Published private(set) var entries: [ClipboardEntry] = []
    /// A completed capture transaction, including a repeated copy of an existing item.
    var onCapture: ((UUID) -> Void)?
    @Published private(set) var boards: [ClipboardPinboard] = []
    @Published private(set) var isLoading = true
    @Published var lastError: String?
    @Published var paused = false {
        didSet {
            // Pausing is a privacy boundary: resuming must not ingest anything
            // that was copied while collection was suspended.
            captureGeneration += 1
            lastChangeCount = pasteboard.changeCount
        }
    }
    @Published var settings: Settings {
        didSet {
            guard settings != oldValue else { return }
            captureGeneration += 1
            lastChangeCount = pasteboard.changeCount
            if let data = try? JSONEncoder().encode(settings.bounded) { defaults.set(data, forKey: Self.settingsKey) }
            trim()
            scheduleSave()
        }
    }

    let directory: URL
    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private let now: () -> Date
    private let isolated: Bool
    private let queue = DispatchQueue(label: "com.kyw.allofmacos.clipboard-storage", qos: .utility)
    private var timer: Timer?
    private var lastChangeCount: Int
    private var captureGeneration = 0
    private var digests: [UUID: String] = [:]
    private var loadingTask: Task<Void, Never>?
    private var captureTasks: [Task<Void, Never>] = []
    private var saveTask: Task<Void, Never>?
    private var storageWritable = true
    private var pendingSave = false
    private var lastTrimDate: Date = .distantPast

    private struct Document: Codable {
        var version = 1
        var entries: [ClipboardEntry]
        var boards: [ClipboardPinboard]
    }

    init(directory: URL? = nil, pasteboard: NSPasteboard? = nil, defaults: UserDefaults? = nil,
         now: @escaping () -> Date = Date.init) {
        let isolated = PresetManager.isRunningTests || PresetManager.isUIPreview ||
            ProcessInfo.processInfo.arguments.contains("--aom-ui-preview") ||
            Bundle.main.bundleIdentifier?.hasSuffix(".preview") == true
        let token = UUID().uuidString
        self.isolated = isolated || pasteboard != nil
        self.directory = directory ?? (isolated
            ? FileManager.default.temporaryDirectory.appendingPathComponent("AOMClipboard-\(token)", isDirectory: true)
            : FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
                .appendingPathComponent("AllOfMacOS/Clipboard", isDirectory: true))
        self.pasteboard = pasteboard ?? (isolated ? NSPasteboard(name: .init("AOMClipboard.\(token)")) : .general)
        self.defaults = defaults ?? (isolated ? UserDefaults(suiteName: "AOMClipboard.\(token)")! : .standard)
        self.now = now
        self.lastChangeCount = self.pasteboard.changeCount
        if let data = self.defaults.data(forKey: Self.settingsKey), let settings = try? JSONDecoder().decode(Settings.self, from: data) {
            self.settings = settings.bounded
        } else { self.settings = Settings() }
        loadingTask = Task { [weak self] in await self?.loadFromDisk() }
    }

    deinit { timer?.invalidate(); saveTask?.cancel() }

    func ready() async { await loadingTask?.value }

    func start() {
        guard timer == nil else { return }
        // Do not capture the user's pre-existing clipboard merely by opening AOM.
        lastChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.15
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        captureGeneration += 1
        lastChangeCount = pasteboard.changeCount
    }

    func poll(sourceName: String? = nil, sourceBundleID: String? = nil) {
        let count = pasteboard.changeCount
        guard !isLoading else { lastChangeCount = count; return }
        if now().timeIntervalSince(lastTrimDate) >= 60 { trim(); lastTrimDate = now() }
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard settings.enabled, !paused else { return }
        let frontmost = isolated ? nil : NSWorkspace.shared.frontmostApplication
        let bundleID = sourceBundleID ?? frontmost?.bundleIdentifier
        let appName = sourceName ?? frontmost?.localizedName
        guard !settings.ignoredApps.contains(where: { $0.caseInsensitiveCompare(bundleID ?? "") == .orderedSame }) else { return }
        guard let boardItems = pasteboard.pasteboardItems, !boardItems.isEmpty, boardItems.count <= 32 else { return }
        // Check the entire transaction before reading any payload. A concealed
        // marker on a later item protects the earlier items too.
        guard !boardItems.contains(where: { item in item.types.contains { Self.excludedTypes.contains($0.rawValue) } }) else { return }
        var items: [[String: Data]] = []
        var total = 0
        for boardItem in boardItems {
            var item: [String: Data] = [:]
            for type in boardItem.types.prefix(64) where Self.supportedTypes.contains(type.rawValue) {
                guard let data = boardItem.data(forType: type) else { continue }
                guard data.count <= Self.maximumEntryBytes - total else { lastError = StoreError.tooLarge.localizedDescription; return }
                total += data.count
                item[type.rawValue] = data
            }
            if !item.isEmpty { items.append(item) }
        }
        // A promised representation can change while its source supplies data.
        guard !items.isEmpty, pasteboard.changeCount == count else { return }
        let entry = ClipboardEntry.captured(items: items, sourceName: appName, sourceBundleID: bundleID, at: now())
        let generation = captureGeneration
        let task = Task { [weak self] in
            guard let self else { return }
            let digest: String = await onQueue { entry.payloadDigest }
            guard generation == captureGeneration, settings.enabled, !paused else { return }
            let capturedID: UUID
            if let index = entries.firstIndex(where: { digests[$0.id] == digest }) {
                var existing = entries.remove(at: index)
                existing.lastCopiedAt = entry.lastCopiedAt
                existing.sourceName = entry.sourceName
                existing.sourceBundleID = entry.sourceBundleID
                entries.insert(existing, at: 0)
                capturedID = existing.id
            } else {
                capturedID = entry.id
                entries.insert(entry, at: 0)
                digests[entry.id] = digest
            }
            trim()
            scheduleSave()
            if entries.contains(where: { $0.id == capturedID }) { onCapture?(capturedID) }
        }
        captureTasks.append(task)
        if captureTasks.count > 64 { captureTasks.removeFirst(captureTasks.count - 64) }
    }

    func filtered(query: String = "", kind: ClipboardEntry.Kind? = nil, source: String? = nil,
                  board: UUID? = nil, since: Date? = nil) -> [ClipboardEntry] {
        let terms = query.split(whereSeparator: \.isWhitespace).map(String.init)
        return entries.filter { entry in
            (kind == nil || entry.kind == kind) &&
            (source == nil || entry.sourceBundleID == source || entry.sourceName == source) &&
            (board == nil || entry.pinboardIDs.contains(board!)) &&
            (since == nil || entry.lastCopiedAt >= since!) &&
            terms.allSatisfy { term in
                [entry.title, entry.text ?? "", entry.sourceName ?? "", entry.sourceBundleID ?? ""]
                    .contains { $0.localizedStandardContains(term) }
            }
        }
    }

    /// Creates a local reusable clip without changing the system pasteboard.
    /// Pinboards and history share the same stored entry format.
    @discardableResult
    func createTextItem(_ text: String) -> ClipboardEntry? {
        let cleaned = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleaned.isEmpty, text.utf8.count <= Self.maximumEntryBytes else {
            if text.utf8.count > Self.maximumEntryBytes {
                lastError = StoreError.tooLarge.localizedDescription
            }
            return nil
        }
        let entry = ClipboardEntry.captured(
            items: [[NSPasteboard.PasteboardType.string.rawValue: Data(text.utf8)]],
            sourceName: "All of MacOS", sourceBundleID: "com.kyw.allofmacos",
            at: now())
        entries.insert(entry, at: 0)
        let task = Task { [weak self] in
            guard let self else { return }
            let digest = await onQueue { entry.payloadDigest }
            if entries.contains(where: { $0.id == entry.id }) {
                digests[entry.id] = digest
            }
        }
        captureTasks.append(task)
        trim()
        scheduleSave()
        return entries.first { $0.id == entry.id }
    }

    @discardableResult
    func createBoard(name: String, color: String = "blue") -> ClipboardPinboard {
        let board = ClipboardPinboard(name: String(name.trimmingCharacters(in: .whitespacesAndNewlines).prefix(100)), color: color)
        guard !board.name.isEmpty, boards.count < 100 else { return board }
        boards.append(board)
        scheduleSave()
        return board
    }

    func renameBoard(id: UUID, name: String) {
        let name = String(name.trimmingCharacters(in: .whitespacesAndNewlines).prefix(100))
        guard !name.isEmpty, let index = boards.firstIndex(where: { $0.id == id }) else { return }
        boards[index].name = name
        scheduleSave()
    }

    func setBoardColor(id: UUID, color: String) {
        guard ["red", "orange", "yellow", "green", "blue", "purple"].contains(color),
              let index = boards.firstIndex(where: { $0.id == id }) else { return }
        boards[index].color = color
        scheduleSave()
    }

    func deleteBoard(id: UUID) {
        boards.removeAll { $0.id == id }
        for index in entries.indices { entries[index].pinboardIDs.remove(id) }
        trim()
        scheduleSave()
    }

    func pin(entryID: UUID, boardID: UUID) {
        guard boards.contains(where: { $0.id == boardID }), let index = entries.firstIndex(where: { $0.id == entryID }) else { return }
        entries[index].pinboardIDs.insert(boardID)
        scheduleSave()
    }

    func unpin(entryID: UUID, boardID: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == entryID }) else { return }
        entries[index].pinboardIDs.remove(boardID)
        trim()
        scheduleSave()
    }

    func rename(entryID: UUID, title: String) {
        let title = String(title.trimmingCharacters(in: .whitespacesAndNewlines).prefix(200))
        guard !title.isEmpty, let index = entries.firstIndex(where: { $0.id == entryID }) else { return }
        entries[index].title = title
        scheduleSave()
    }

    func editText(entryID: UUID, text: String) {
        guard let index = entries.firstIndex(where: { $0.id == entryID }), [.text, .link, .color].contains(entries[index].kind) else { return }
        guard text.utf8.count <= Self.maximumEntryBytes else { lastError = StoreError.tooLarge.localizedDescription; return }
        let old = entries[index]
        var edited = ClipboardEntry.captured(items: [[NSPasteboard.PasteboardType.string.rawValue: Data(text.utf8)]],
                                             sourceName: old.sourceName, sourceBundleID: old.sourceBundleID, at: old.createdAt)
        edited.id = old.id
        edited.title = old.title
        edited.lastCopiedAt = old.lastCopiedAt
        edited.pinboardIDs = old.pinboardIDs
        entries[index] = edited
        digests[edited.id] = nil
        let task = Task { [weak self] in
            guard let self else { return }
            let digest = await onQueue { edited.payloadDigest }
            if entries.first(where: { $0.id == edited.id })?.items == edited.items { digests[edited.id] = digest }
        }
        captureTasks.append(task)
        trim()
        scheduleSave()
    }

    @discardableResult
    func duplicate(entryID: UUID) -> ClipboardEntry? {
        guard var entry = entries.first(where: { $0.id == entryID }) else { return nil }
        let digest = digests[entry.id]
        entry.id = UUID()
        entry.title += " Copy"
        entry.createdAt = now()
        entry.lastCopiedAt = now()
        entries.insert(entry, at: 0)
        digests[entry.id] = digest
        trim()
        scheduleSave()
        return entries.first { $0.id == entry.id }
    }

    func delete(entryID: UUID) {
        entries.removeAll { $0.id == entryID }
        digests[entryID] = nil
        scheduleSave()
    }

    func clearUnpinned() {
        // In-flight capture belongs to the history being cleared as well.
        captureGeneration += 1
        entries.removeAll { $0.pinboardIDs.isEmpty }
        pruneDigests()
        scheduleSave()
    }

    /// Writes all selected rich items in order. Plain text explicitly flattens
    /// them into one string; no key event or application activation occurs here.
    @discardableResult
    func write(entryIDs: [UUID], plainText: Bool = false, separator: String = "\n") throws -> Bool {
        var seen = Set<UUID>()
        let selected = entryIDs.filter { seen.insert($0).inserted }.compactMap { id in entries.first { $0.id == id } }
        guard !selected.isEmpty, selected.count == seen.count else { throw StoreError.emptySelection }
        let objects: [NSPasteboardItem]
        if plainText {
            let parts = selected.compactMap { entry -> String? in
                if let text = entry.text { return text }
                if !entry.fileURLs.isEmpty { return entry.fileURLs.map(\.path).joined(separator: separator) }
                return nil
            }
            guard parts.count == selected.count else { throw StoreError.cannotWrite }
            let text = parts.joined(separator: separator)
            guard text.utf8.count <= Self.maximumEntryBytes else { throw StoreError.tooLarge }
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            objects = [item]
        } else {
            guard selected.reduce(0, { $0 + $1.byteCount }) <= settings.bounded.maxBytes else { throw StoreError.tooLarge }
            objects = selected.flatMap(\.items).map { data in
                let item = NSPasteboardItem()
                for (type, value) in data { item.setData(value, forType: .init(type)) }
                return item
            }
        }
        guard !objects.isEmpty else { throw StoreError.emptySelection }
        pasteboard.clearContents()
        let result = pasteboard.writeObjects(objects)
        lastChangeCount = pasteboard.changeCount
        guard result else { throw StoreError.cannotWrite }
        let copiedAt = now()
        for index in entries.indices where seen.contains(entries[index].id) { entries[index].lastCopiedAt = copiedAt }
        entries.sort { $0.lastCopiedAt > $1.lastCopiedAt }
        scheduleSave()
        return true
    }

    /// Tests and application termination can await durable storage without
    /// sleeping or reading a partially written snapshot.
    func flush() async {
        await ready()
        let tasks = captureTasks
        for task in tasks { await task.value }
        captureTasks.removeAll()
        saveTask?.cancel()
        saveTask = nil
        if pendingSave { await persist() }
    }

    private func trim() {
        let limits = settings.bounded
        let before = entries.count
        if limits.retentionDays > 0 {
            let cutoff = now().addingTimeInterval(-Double(limits.retentionDays) * 86_400)
            entries.removeAll { $0.pinboardIDs.isEmpty && $0.lastCopiedAt < cutoff }
        }
        var bytes = entries.reduce(0) { $0 + $1.byteCount }
        while entries.count > limits.maxEntries || bytes > limits.maxBytes {
            // Pinned content is retained preferentially, but a hard memory cap
            // still applies if all remaining items are pinned.
            guard let index = entries.lastIndex(where: { $0.pinboardIDs.isEmpty }) ?? entries.indices.last else { break }
            bytes -= entries[index].byteCount
            if !entries[index].pinboardIDs.isEmpty { lastError = "Clipboard storage is full. The oldest pinned item was removed to keep the memory limit." }
            entries.remove(at: index)
        }
        if entries.count != before { pruneDigests(); scheduleSave() }
    }

    private func pruneDigests() {
        let ids = Set(entries.map(\.id))
        digests = digests.filter { ids.contains($0.key) }
    }

    private func scheduleSave() {
        pendingSave = true
        guard !isLoading, storageWritable else { return }
        saveTask?.cancel()
        saveTask = Task { [weak self] in
            do { try await Task.sleep(nanoseconds: 800_000_000) } catch { return }
            await self?.persist()
        }
    }

    private func persist() async {
        guard storageWritable, !isLoading, pendingSave else { return }
        pendingSave = false
        let document = Document(entries: entries, boards: boards)
        let directory = directory
        let success = await onQueue { () -> Bool in
            do {
                try Self.prepare(directory: directory)
                let file = directory.appendingPathComponent("history-v1.json")
                if try Self.isSymlink(file) { throw StoreError.storageUnavailable }
                let data = try JSONEncoder().encode(document)
                try data.write(to: file, options: .atomic)
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
                return true
            } catch { return false }
        }
        if !success { pendingSave = true; lastError = StoreError.storageUnavailable.localizedDescription }
    }

    private func loadFromDisk() async {
        let directory = directory
        let loaded: Result<(Document, [UUID: String]), Error> = await onQueue {
            do {
                let file = directory.appendingPathComponent("history-v1.json")
                guard FileManager.default.fileExists(atPath: file.path) else { return .success((Document(entries: [], boards: []), [:])) }
                guard !(try Self.isSymlink(directory)), !(try Self.isSymlink(file)) else { throw StoreError.invalidArchive }
                let attributes = try FileManager.default.attributesOfItem(atPath: file.path)
                guard (attributes[.size] as? NSNumber)?.intValue ?? Int.max <= 300 * 1_024 * 1_024 else { throw StoreError.invalidArchive }
                let document = try JSONDecoder().decode(Document.self, from: Data(contentsOf: file))
                guard document.version == 1, document.entries.count <= 10_000, document.boards.count <= 100,
                      Set(document.entries.map(\.id)).count == document.entries.count,
                      Set(document.boards.map(\.id)).count == document.boards.count,
                      document.entries.allSatisfy({ $0.byteCount <= Self.maximumEntryBytes && $0.items.count <= 32 && $0.items.allSatisfy { $0.count <= 64 } }),
                      document.entries.reduce(0, { $0 + $1.byteCount }) <= 200 * 1_024 * 1_024 else { throw StoreError.invalidArchive }
                return .success((document, Dictionary(uniqueKeysWithValues: document.entries.map { ($0.id, $0.payloadDigest) })))
            } catch { return .failure(error) }
        }
        switch loaded {
        case .success(let (document, digests)):
            entries = document.entries.sorted { $0.lastCopiedAt > $1.lastCopiedAt }
            boards = document.boards + boards.filter { current in !document.boards.contains { $0.id == current.id } }
            self.digests = digests
            let boardIDs = Set(boards.map(\.id))
            for index in entries.indices { entries[index].pinboardIDs.formIntersection(boardIDs) }
        case .failure:
            storageWritable = false
            lastError = StoreError.invalidArchive.localizedDescription
        }
        isLoading = false
        trim()
        if pendingSave { scheduleSave() }
    }

    private func onQueue<T>(_ work: @escaping () -> T) async -> T {
        await withCheckedContinuation { continuation in
            queue.async { continuation.resume(returning: work()) }
        }
    }

    nonisolated private static func isSymlink(_ url: URL) throws -> Bool {
        guard FileManager.default.fileExists(atPath: url.path) else { return false }
        return try FileManager.default.attributesOfItem(atPath: url.path)[.type] as? FileAttributeType == .typeSymbolicLink
    }

    nonisolated private static func prepare(directory: URL) throws {
        guard !(try isSymlink(directory)) else { throw StoreError.storageUnavailable }
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: directory.path)
    }
}
