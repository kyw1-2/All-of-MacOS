    func deleteBoard(id: UUID) {
        boards.removeAll { $0.id == id }
        for index in entries.indices { entries[index].pinboardIDs.remove(id) }
        trim()
        scheduleSave()
    }

    func pin(entryID: UUID, boardID: UUID) {
        guard boards.contains(where: { $0.id == boardID }), let index = entries.firstIndex(where: { $0.id == entryID }) else { return }
        entries[index].pinboardIDs.insert(boardID)
        scheduleSave()
    }

    func unpin(entryID: UUID, boardID: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == entryID }) else { return }
        entries[index].pinboardIDs.remove(boardID)
        trim()
        scheduleSave()
    }

    func rename(entryID: UUID, title: String) {
        let title = String(title.trimmingCharacters(in: .whitespacesAndNewlines).prefix(200))
        guard !title.isEmpty, let index = entries.firstIndex(where: { $0.id == entryID }) else { return }
        entries[index].title = title
        scheduleSave()
    }

    /// Plain text is always present; RTF is kept only when it adds formatting.
    static func textRepresentations(_ text: String, rtfData: Data?) -> [String: Data] {
        var item = [NSPasteboard.PasteboardType.string.rawValue: Data(text.utf8)]
        if let rtfData, !rtfData.isEmpty, hasFormatting(rtfData) {
            item[NSPasteboard.PasteboardType.rtf.rawValue] = rtfData
        }
        return item
    }

    private static func hasFormatting(_ rtf: Data) -> Bool {
        guard let attributed = try? NSAttributedString(
            data: rtf, options: [.documentType: NSAttributedString.DocumentType.rtf],
            documentAttributes: nil), attributed.length > 0 else { return false }
        var formatted = false
        attributed.enumerateAttributes(in: NSRange(location: 0, length: attributed.length)) { attrs, _, stop in
            if let font = attrs[.font] as? NSFont,
               !NSFontManager.shared.traits(of: font).intersection([.boldFontMask, .italicFontMask]).isEmpty {
                formatted = true
            }
            for key in [NSAttributedString.Key.underlineStyle, .strikethroughStyle] {
                if let value = attrs[key] as? NSNumber, value.intValue != 0 { formatted = true }
            }
            if formatted { stop.pointee = true }
        }
        return formatted
    }

    func editText(entryID: UUID, text: String, rtfData: Data? = nil) {
        guard let index = entries.firstIndex(where: { $0.id == entryID }), [.text, .link, .color].contains(entries[index].kind) else { return }
        guard text.utf8.count <= Self.maximumEntryBytes else { lastError = StoreError.tooLarge.localizedDescription; return }
        let old = entries[index]
        var representations = old.kind == .text ? Self.textRepresentations(text, rtfData: rtfData)
            : [NSPasteboard.PasteboardType.string.rawValue: Data(text.utf8)]
        if old.kind == .color, let color = ClipboardColorEditor.color(text),
           let native = color.pasteboardPropertyList(forType: .color) as? Data {
            representations[NSPasteboard.PasteboardType.color.rawValue] = native
        }
        var edited = ClipboardEntry.captured(items: [representations],
                                             sourceName: old.sourceName, sourceBundleID: old.sourceBundleID, at: old.createdAt)
        edited.id = old.id
        edited.contentRevision = UUID()
        edited.title = old.title
        edited.lastCopiedAt = old.lastCopiedAt
        edited.pinboardIDs = old.pinboardIDs
        entries[index] = edited
        digests[edited.id] = nil
        let task = Task { [weak self] in
            guard let self else { return }
            let digest = await onQueue { edited.payloadDigest }
            if entries.first(where: { $0.id == edited.id })?.items == edited.items { digests[edited.id] = digest }
        }
        captureTasks.append(task)
        trim()
        scheduleSave()
    }

    @discardableResult
    func duplicate(entryID: UUID) -> ClipboardEntry? {
        guard var entry = entries.first(where: { $0.id == entryID }) else { return nil }
        entry.id = UUID()
        entry.duplicatedFrom = entryID
        entry.title += " Copy"
        entry.createdAt = now()
        entry.lastCopiedAt = now()
        entries.insert(entry, at: 0)
        // The duplicate has its own identity. Do not adopt the source's cached
        // digest blindly: recompute it for the new entry. De-duplication also
        // prefers a non-duplicate match, so a later copy of the original is
        // credited to the original rather than to this "Copy".
        let duplicated = entry
        let task = Task { [weak self] in
            guard let self else { return }
            let digest = await onQueue { duplicated.payloadDigest }
            if entries.contains(where: { $0.id == duplicated.id }) { digests[duplicated.id] = digest }
        }
        captureTasks.append(task)
        trim()
        scheduleSave()
        return entries.first { $0.id == entry.id }
    }

    /// The entry a fresh copy should be credited to. Among existing entries
    /// with the same payload, an original (`duplicatedFrom == nil`) wins over a
    /// user-made copy so the copy cannot absorb the original's timestamp and
    /// age it out of the history first.
    private static func deduplicationIndex(in entries: [ClipboardEntry], digests: [UUID: String],
                                           digest: String, excluding id: UUID) -> Int? {
        let matches = entries.indices.filter { entries[$0].id != id && digests[entries[$0].id] == digest }
        return matches.first(where: { entries[$0].duplicatedFrom == nil }) ?? matches.first
    }

    func delete(entryID: UUID) { delete(entryIDs: [entryID]) }

    func delete(entryIDs: [UUID]) {
        let ids = Set(entryIDs)
        rememberDeletion(entries.filter { ids.contains($0.id) })
        entries.removeAll { ids.contains($0.id) }
        pruneDigests()
        scheduleSave()
    }

    private func rememberDeletion(_ deleted: [ClipboardEntry]) {
        guard !deleted.isEmpty else { return }
        deletionHistory.append(deleted)
        // Undo is session-only and bounded independently of permanent pinboards.
        while deletionHistory.count > 20 ||
              (deletionHistory.count > 1 && deletionHistory.flatMap { $0 }.reduce(0, { $0 + $1.byteCount }) > 100 * 1_024 * 1_024) {
            deletionHistory.removeFirst()
        }
        canUndoDeletion = true
    }

    @discardableResult
    func undoDeletion() -> [UUID] {
        guard let deleted = deletionHistory.popLast() else { return [] }
        let boardIDs = Set(boards.map(\.id))
        let existing = Set(entries.map(\.id))
        let restored = deleted.filter { !existing.contains($0.id) }.map { entry -> ClipboardEntry in
            var entry = entry
            entry.pinboardIDs.formIntersection(boardIDs)
            // A restored item gets a fresh retention period, so Undo is not
            // immediately undone by the next periodic expiration pass.
            entry.lastCopiedAt = now()
            return entry
        }
        entries.insert(contentsOf: restored, at: 0)
        canUndoDeletion = !deletionHistory.isEmpty
        let task = Task { [weak self] in
            guard let self else { return }
            let values = await onQueue { restored.map { ($0.id, $0.payloadDigest) } }
            for (id, digest) in values where entries.contains(where: { $0.id == id }) { digests[id] = digest }
        }
        captureTasks.append(task)
        scheduleSave()
        scheduleImageIndexing()
        return restored.map(\.id)
    }

    /// How many unpinned items a smaller item limit would delete right away
    /// (Paste's "reduce history limit" question). Pinned items never count.
    func itemsRemoved(byMaxEntries newLimit: Int) -> Int {
        let limit = Settings(maxEntries: newLimit).bounded.maxEntries
        return max(0, entries.filter { $0.pinboardIDs.isEmpty }.count - limit)
    }

    /// Applies a new item limit; deleted items can be restored with Undo.
    func applyMaxEntries(_ newLimit: Int) {
        let unpinned = entries.filter { $0.pinboardIDs.isEmpty }
        let limit = Settings(maxEntries: newLimit).bounded.maxEntries
        if unpinned.count > limit { rememberDeletion(Array(unpinned.suffix(unpinned.count - limit))) }
        settings.maxEntries = newLimit
    }

    /// Erase History: every unpinned item goes; pinboards and pinned items stay.
    func eraseHistory() { clearUnpinned() }

    func clearUnpinned() {
        // In-flight capture belongs to the history being cleared as well.
        captureGeneration += 1
        rememberDeletion(entries.filter { $0.pinboardIDs.isEmpty })
        entries.removeAll { $0.pinboardIDs.isEmpty }
        pruneDigests()
        scheduleSave()
    }

    func copyRecognizedText(entryID: UUID) throws {
        guard let text = entries.first(where: { $0.id == entryID })?.recognizedText, !text.isEmpty else { throw StoreError.emptySelection }
        pasteboard.clearContents()
        let written = pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        guard written else { throw StoreError.cannotWrite }
        ClipboardAudioFeedback.copy()
    }

    /// Writes all selected rich items in order. Plain text explicitly flattens
    /// them into one string; no key event or application activation occurs here.
    @discardableResult
    func write(entryIDs: [UUID], plainText: Bool = false, separator: String = "\n", playSound: Bool = true) throws -> Bool {
        let selected = try selectedEntries(entryIDs)
        let payload = try ClipboardWritePayload.make(selected, plainText: plainText, separator: separator)
        _ = try commitWrite(payload, ids: Set(selected.map(\.id)), playSound: playSound)
        return true
    }

    private let writeQueue = DispatchQueue(label: "com.kyw.allofmacos.clipboard-output", qos: .userInitiated)
    var prepareWriteOverride: (@Sendable ([ClipboardEntry], Bool, String) throws -> [[String: Data]])?
    /// Selection and focus stay responsive while a large rich payload is built.
    /// A newer copy/cancel invalidates this request before replacing the board.
    func writeAsync(entryIDs: [UUID], plainText: Bool = false, separator: String = "\n", playSound: Bool = true) async throws -> Int {
        let selected = try selectedEntries(entryIDs)
        let expected = pasteboard.changeCount
        let prepare = prepareWriteOverride
        let payload: [[String: Data]] = try await withCheckedThrowingContinuation { continuation in
            writeQueue.async {
                continuation.resume(with: Result {
                    if let prepare { return try prepare(selected, plainText, separator) }
                    return try ClipboardWritePayload.make(selected, plainText: plainText, separator: separator)
                })
            }
        }
        try Task.checkCancellation()
        guard pasteboard.changeCount == expected else { throw StoreError.cannotWrite }
        let current = try selectedEntries(entryIDs)
        guard current.map(\.contentVersion) == selected.map(\.contentVersion) else { throw StoreError.emptySelection }
        return try commitWrite(payload, ids: Set(selected.map(\.id)), playSound: playSound)
    }

    private func selectedEntries(_ entryIDs: [UUID]) throws -> [ClipboardEntry] {
        var seen = Set<UUID>()
        let ids = entryIDs.filter { seen.insert($0).inserted }
        let selected: [ClipboardEntry]
        if ids.count == 1 { selected = entries.first(where: { $0.id == ids[0] }).map { [$0] } ?? [] }
        else {
            let indexed = Dictionary(entries.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first })
            selected = ids.compactMap { indexed[$0] }
        }
        guard !selected.isEmpty, selected.count == ids.count else { throw StoreError.emptySelection }
        return selected
    }

    private func commitWrite(_ payload: [[String: Data]], ids seen: Set<UUID>, playSound: Bool) throws -> Int {
        let objects = payload.map { data in
            let item = NSPasteboardItem()
            for (type, value) in data { item.setData(value, forType: .init(type)) }
            return item
        }
        guard !objects.isEmpty else { throw StoreError.emptySelection }
        pasteboard.clearContents()
        let result = pasteboard.writeObjects(objects)
        lastChangeCount = pasteboard.changeCount
        guard result else { throw StoreError.cannotWrite }
        let copiedAt = now()
        if defersBackgroundUpdates {
            for id in seen { pendingTouches[id] = copiedAt }
        } else {
            // One published mutation instead of one per item plus a sort.
            var updated = entries
            for index in updated.indices where seen.contains(updated[index].id) { updated[index].lastCopiedAt = copiedAt }
            updated.sort { $0.lastCopiedAt > $1.lastCopiedAt }
            entries = updated
            scheduleSave()
        }
        if playSound { ClipboardAudioFeedback.copy() }
        return lastChangeCount
    }

    /// Tests and application termination can await durable storage without
    /// sleeping or reading a partially written snapshot.
    func flush() async {
        await ready()
        let tasks = captureTasks
        for task in tasks { await task.value }
        captureTasks.removeAll()
        saveTask?.cancel()
        saveTask = nil
        if pendingSave { await persist() }
    }

    private func trim() {
        let limits = settings.bounded
        let before = entries.count
        if limits.retentionDays > 0 {
            let cutoff = now().addingTimeInterval(-Double(limits.retentionDays) * 86_400)
            // Mutating the published array re-renders an open panel, so only
            // touch it when something actually expires.
            if entries.contains(where: { $0.pinboardIDs.isEmpty && $0.lastCopiedAt < cutoff }) {
                entries.removeAll { $0.pinboardIDs.isEmpty && $0.lastCopiedAt < cutoff }
            }
        }
        // Retention limits cover history only. Pinboards are explicit durable
        // collections and are never silently evicted to make room for history.
        var unpinned = entries.filter { $0.pinboardIDs.isEmpty }
        var bytes = unpinned.reduce(0) { $0 + $1.byteCount }
        var removed = Set<UUID>()
        while unpinned.count > limits.maxEntries || bytes > limits.maxBytes {
            guard let oldest = unpinned.popLast() else { break }
            bytes -= oldest.byteCount
            removed.insert(oldest.id)
        }
        if !removed.isEmpty { entries.removeAll { removed.contains($0.id) } }
        if entries.count != before { pruneDigests(); scheduleSave() }
    }

    var pinnedBytes: Int { entries.filter { !$0.pinboardIDs.isEmpty }.reduce(0) { $0 + $1.byteCount } }
    var historyBytes: Int { entries.filter { $0.pinboardIDs.isEmpty }.reduce(0) { $0 + $1.byteCount } }

    /// Finish pending copy transactions before a native stack paste chooses its
    /// next item. This does not force a disk write or change the clipboard.
    func finishPendingCaptures() async {
        let tasks = captureTasks
        for task in tasks { await task.value }
    }

    /// Adds an image as a new clipboard item (used for edits that keep the
    /// original, such as Remove Background). Pinboards of the source carry over.
    @discardableResult
    func createImageItem(_ image: CGImage, from source: ClipboardEntry? = nil) -> ClipboardEntry? {
        guard let data = NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:]) else { return nil }
        guard data.count <= Self.maximumEntryBytes else { lastError = StoreError.tooLarge.localizedDescription; return nil }
        var entry = ClipboardEntry.captured(items: [[NSPasteboard.PasteboardType.png.rawValue: data]],
                                            sourceName: "All of MacOS", sourceBundleID: "com.kyw.allofmacos", at: now())
        entry.pinboardIDs = source?.pinboardIDs ?? []
        entries.insert(entry, at: 0)
        let inserted = entry
        let task = Task { [weak self] in
            guard let self else { return }
            let digest = await onQueue { inserted.payloadDigest }
            if entries.contains(where: { $0.id == inserted.id }) { digests[inserted.id] = digest }
        }
        captureTasks.append(task)
        trim()
        scheduleSave()
        scheduleImageIndexing()
        return entries.first { $0.id == entry.id }
    }

    func editImage(entryID: UUID, image: CGImage) {
        guard let index = entries.firstIndex(where: { $0.id == entryID }), entries[index].kind == .image,
              let data = NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:]) else { return }
        guard data.count <= Self.maximumEntryBytes else { lastError = StoreError.tooLarge.localizedDescription; return }
        entries[index].contentRevision = UUID()
        entries[index].items = [[NSPasteboard.PasteboardType.png.rawValue: data]]
        entries[index].text = nil
        entries[index].recognizedText = nil
        entries[index].recognizedImageDigest = nil
        attemptedImages.remove(entryID)
        digests[entryID] = nil
        let edited = entries[index]
        let task = Task { [weak self] in
            guard let self else { return }
            let digest = await onQueue { edited.payloadDigest }
            if entries.first(where: { $0.id == edited.id })?.items == edited.items { digests[edited.id] = digest }
        }
        captureTasks.append(task)
        scheduleSave()
        scheduleImageIndexing()
    }

    private func scheduleImageIndexing() {
        guard indexingTask == nil else { return }
        indexingTask = Task { [weak self] in
            guard let self else { return }
            indexingImages = true
            defer { indexingImages = false; indexingTask = nil }
            while !Task.isCancelled,
                  let entry = entries.first(where: { $0.kind == .image && $0.recognizedImageDigest == nil && !attemptedImages.contains($0.id) }),
                  let data = entry.imageData {
                attemptedImages.insert(entry.id)
                // The Capture Text engine (multi-script, CJK-aware) indexes
                // image text, so searching Korean/Japanese/Chinese finds it.
                let digest: String = await onQueue { entry.payloadDigest }
                let text = await TextRecognitionService.recognizeForIndexing(imageData: data)
                let result: (String, String)? = text.map { ($0, digest) }
                // Applying a result re-renders an open clipboard shelf; wait
                // until it closes so browsing never stutters behind indexing.
                while defersBackgroundUpdates, !Task.isCancelled {
                    try? await Task.sleep(nanoseconds: 400_000_000)
                }
                guard let result, let index = entries.firstIndex(where: { $0.id == entry.id }),
                      entries[index].items == entry.items else { continue }
                var updated = entries[index]
                updated.recognizedText = result.0
                updated.recognizedImageDigest = result.1
                entries[index] = updated
                scheduleSave()
            }
        }
    }

    private func pruneDigests() {
        let ids = Set(entries.map(\.id))
        digests = digests.filter { ids.contains($0.key) }
        attemptedImages.formIntersection(ids)
    }

    private func scheduleSave() {
        pendingSave = true
        guard !isLoading, storageWritable else { return }
        saveTask?.cancel()
        saveTask = Task { [weak self] in
            do { try await Task.sleep(nanoseconds: 800_000_000) } catch { return }
            await self?.persist()
        }
    }

    private func persist() async {
        guard storageWritable, !isLoading, pendingSave else { return }
        pendingSave = false
        let document = Document(entries: entries, boards: boards)
        let directory = directory
        let encrypt = !isolated
        let success = await onQueue { () -> Bool in
            do {
                try Self.prepare(directory: directory)
                let file = directory.appendingPathComponent(encrypt ? "history-v2.encrypted" : "history-v1.json")
                if try Self.isSymlink(file) { throw StoreError.storageUnavailable }
                let plain = try JSONEncoder().encode(document)
                let data = try encrypt ? ClipboardArchiveEncryption.encrypt(plain) : plain
                try data.write(to: file, options: .atomic)
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
                if encrypt {
                    let legacy = directory.appendingPathComponent("history-v1.json")
                    // Retire plaintext only after an atomic encrypted write succeeds.
                    // A failure before this point leaves the legacy file untouched.
                    if FileManager.default.fileExists(atPath: legacy.path), !(try Self.isSymlink(legacy)) {
                        try FileManager.default.removeItem(at: legacy)
                    }
                }
                return true
            } catch { return false }
        }
        if !success { pendingSave = true; lastError = StoreError.storageUnavailable.localizedDescription }
    }

    private func loadFromDisk() async {
        if let injected = loadFailureOverride {
            loadFailureOverride = nil
            handleStorageFailure(injected)
            isLoading = false
            return
        }
        let directory = directory
        let encryptedURL = directory.appendingPathComponent("history-v2.encrypted")
        let encryptedExists = !isolated && FileManager.default.fileExists(atPath: encryptedURL.path)
        let loaded: Result<(Document, [UUID: String]), Error> = await onQueue {
            do {
                let file = encryptedExists ? encryptedURL : directory.appendingPathComponent("history-v1.json")
                guard FileManager.default.fileExists(atPath: file.path) else { return .success((Document(entries: [], boards: []), [:])) }
                guard !(try Self.isSymlink(directory)), !(try Self.isSymlink(file)) else { throw StoreError.invalidArchive }
                let bytes = try Data(contentsOf: file, options: .mappedIfSafe)
                let plain = try encryptedExists ? ClipboardArchiveEncryption.decrypt(bytes) : bytes
                let document = try JSONDecoder().decode(Document.self, from: plain)
                guard document.version == 1, document.boards.count <= 100,
                      Set(document.entries.map(\.id)).count == document.entries.count,
                      Set(document.boards.map(\.id)).count == document.boards.count,
                      document.entries.allSatisfy({ $0.byteCount <= Self.maximumEntryBytes && $0.items.count <= 32 && $0.items.allSatisfy { $0.count <= 64 } }) else { throw StoreError.invalidArchive }
                return .success((document, Dictionary(uniqueKeysWithValues: document.entries.map { ($0.id, $0.payloadDigest) })))
            } catch { return .failure(error) }
        }
        switch loaded {
        case .success(let (document, digests)):
            storageStatus = .ok
            storageWarning = nil
            storageRetryAttempts = 0
            storageRetryTask?.cancel()
            storageRetryTask = nil
            // Local snippets can be created while the encrypted archive loads.
            let local = entries
            let localIDs = Set(local.map(\.id))
            entries = (local + document.entries.filter { !localIDs.contains($0.id) })
                .sorted { $0.lastCopiedAt > $1.lastCopiedAt }
            boards = document.boards + boards.filter { current in !document.boards.contains { $0.id == current.id } }
            self.digests.merge(digests) { current, _ in current }
            let boardIDs = Set(boards.map(\.id))
            for index in entries.indices { entries[index].pinboardIDs.formIntersection(boardIDs) }
            if !isolated && !encryptedExists { pendingSave = true }
        case .failure(let error):
            handleStorageFailure(error)
        }
        isLoading = false
        trim()
        if pendingSave { scheduleSave() }
        scheduleImageIndexing()
    }

    /// Classifies a failed archive read. A locked or temporarily unavailable
    /// login Keychain is transient: reading can succeed later, so the existing
    /// archive must not be overwritten in the meantime. A corrupt archive, a
    /// missing or rotated key, or a decode failure is not transient.
    nonisolated static func isTransientStorageFailure(_ error: Error) -> Bool {
        if let failure = error as? ClipboardArchiveEncryption.Failure,
           case .keychain = failure { return true }
        return false
    }

    private func handleStorageFailure(_ error: Error) {
        storageStatus = Self.isTransientStorageFailure(error) ? .transientFailure : .unreadableArchive
        storageWarning = Self.storageWarning(for: storageStatus)
        lastError = (error as? ClipboardArchiveEncryption.Failure)?.localizedDescription
            ?? StoreError.invalidArchive.localizedDescription
        if storageStatus == .transientFailure { scheduleStorageRetry() }
    }

    private static func storageWarning(for status: StorageStatus) -> String? {
        switch status {
        case .ok:
            return nil
        case .transientFailure:
            return "Clipboard history is not being saved because the login Keychain is locked or unavailable. New items are kept in memory and saved automatically once the Keychain is available. Your existing history is preserved."
        case .unreadableArchive:
            return "Clipboard history could not be read, so saving is paused to protect the existing file. Use “Recover Clipboard Storage” to archive the unreadable file and resume saving. Your saved file has not been changed."
        }
    }

    private func scheduleStorageRetry() {
        guard storageStatus == .transientFailure, storageRetryTask == nil,
              storageRetryAttempts < Self.storageRetryLimit else { return }
        storageRetryAttempts += 1
        storageRetryTask = Task { [weak self] in
            try? await Task.sleep(nanoseconds: Self.storageRetryDelay)
            guard let self, !Task.isCancelled else { return }
            // Clear the slot before retrying: this task is the one currently in
            // `storageRetryTask`, and `retryStorage` must not cancel itself.
            self.storageRetryTask = nil
            await self.retryStorage()
        }
    }

    /// Retries reading a transiently unavailable archive. Also backs the manual
    /// "Retry" action; a no-op unless the last failure was transient. A
    /// re-entrant call is ignored while a load is already in flight so two
    /// loads can never merge the archive concurrently.
    func retryStorage() async {
        guard storageStatus == .transientFailure, !isLoading else { return }
        storageRetryTask?.cancel()
        storageRetryTask = nil
        isLoading = true
        await loadFromDisk()
        if storageStatus == .ok, pendingSave { await persist() }
    }

    /// User-initiated recovery from a blocked persistence state.
    /// - `.transientFailure`: retry now and reset the automatic retry budget.
    /// - `.unreadableArchive`: move the unreadable archive aside (its bytes are
    ///   preserved under a `.unreadable-<timestamp>` name) and start saving a
    ///   fresh archive.
    func recoverStorage() async {
        switch storageStatus {
        case .ok:
            return
        case .transientFailure:
            storageRetryAttempts = 0
            await retryStorage()
        case .unreadableArchive:
            await quarantineUnreadableArchive()
        }
    }

    private func quarantineUnreadableArchive() async {
        let directory = directory
        let quarantined = await onQueue { () -> Bool in
            do {
                try Self.prepare(directory: directory)
                let stamp = String(Int(Date().timeIntervalSince1970))
                var movedAny = false
                for name in ["history-v2.encrypted", "history-v1.json"] {
                    let file = directory.appendingPathComponent(name)
                    guard FileManager.default.fileExists(atPath: file.path),
                          !(try Self.isSymlink(file)) else { continue }
                    let backup = file.appendingPathExtension("unreadable-\(stamp)")
                    try FileManager.default.moveItem(at: file, to: backup)
                    movedAny = true
                }
                return movedAny
            } catch { return false }
        }
        guard quarantined else {
            lastError = StoreError.storageUnavailable.localizedDescription
            return
        }
        storageStatus = .ok
        storageWarning = nil
        storageRetryAttempts = 0
        pendingSave = true
        await persist()
    }

    private static let storageRetryLimit = 12
    private static let storageRetryDelay: UInt64 = 5_000_000_000

    private func onReadQueue<T>(_ work: @escaping () -> T) async -> T {
        await withCheckedContinuation { continuation in
            readQueue.async { continuation.resume(returning: work()) }
        }
    }

    private func onCaptureQueue<T>(_ work: @escaping () -> T) async -> T {
        await withCheckedContinuation { continuation in
            captureQueue.async { continuation.resume(returning: work()) }
        }
    }

    private func onQueue<T>(_ work: @escaping () -> T) async -> T {
        await withCheckedContinuation { continuation in
            queue.async { continuation.resume(returning: work()) }
        }
    }

    nonisolated private static func isSymlink(_ url: URL) throws -> Bool {
        guard FileManager.default.fileExists(atPath: url.path) else { return false }
        return try FileManager.default.attributesOfItem(atPath: url.path)[.type] as? FileAttributeType == .typeSymbolicLink
    }

    nonisolated private static func prepare(directory: URL) throws {
        guard !(try isSymlink(directory)) else { throw StoreError.storageUnavailable }
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: directory.path)
    }
}

/// Public system sounds provide local feedback without bundling proprietary audio.
@MainActor
enum ClipboardAudioFeedback {
    static func copy() { play("Tink", volume: 0.22) }
    static func paste() { play("Pop", volume: 0.30) }
    private static func play(_ name: String, volume: Float) {
        guard !PresetManager.isRunningTests, !PresetManager.isUIPreview else { return }
        // Off the main thread: NSSound's first play waited for the audio
        // device and froze the shelf mid-animation.
        AOMSystemSound.play(name, volume: volume)
    }
}

