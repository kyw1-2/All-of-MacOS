    /// App choices are inferred from recorded clipboard provenance; they are
    /// never a catalog of installed or hardcoded applications.
    struct AppSource: Identifiable, Equatable {
        let id: String
        let filterValue: String
        let name: String
        let bundleID: String?
        let count: Int
        let lastUsed: Date

        static func collect(from entries: [ClipboardEntry]) -> [AppSource] {
            var indexed: [String: AppSource] = [:]
            for entry in entries {
                let bundleID = entry.sourceBundleID?.trimmingCharacters(in: .whitespacesAndNewlines)
                let bundle = bundleID?.isEmpty == false ? bundleID : nil
                let rawName = entry.sourceName?.trimmingCharacters(in: .whitespacesAndNewlines)
                let name = rawName?.isEmpty == false ? rawName : nil
                guard let source = bundle ?? name else { continue }
                let key = bundle.map { "bundle:" + $0 } ?? ("name:" + source)
                if let old = indexed[key] {
                    indexed[key] = AppSource(id: key, filterValue: source,
                        name: name ?? old.name, bundleID: bundle,
                        count: old.count + 1,
                        lastUsed: max(old.lastUsed, entry.lastCopiedAt))
                } else {
                    indexed[key] = AppSource(id: key, filterValue: source,
                        name: name ?? bundle ?? source, bundleID: bundle,
                        count: 1, lastUsed: entry.lastCopiedAt)
                }
            }
            return indexed.values.sorted {
                if $0.lastUsed != $1.lastUsed { return $0.lastUsed > $1.lastUsed }
                return $0.name.localizedStandardCompare($1.name) == .orderedAscending
            }
        }
    }

    private var appSourceCache: (revision: Int, options: [AppSource])?
    var availableAppSources: [AppSource] {
        if let cached = appSourceCache, cached.revision == revision { return cached.options }
        let options = AppSource.collect(from: entries)
        appSourceCache = (revision, options)
        return options
    }

    @Published private(set) var entries: [ClipboardEntry] = [] { didSet { revision &+= 1 } }
    /// Bumped on every change to `entries` or `boards`; lets views memoise
    /// filtered results instead of re-filtering per card per frame.
    private(set) var revision = 0
    /// A completed capture transaction, including a repeated copy of an existing item.
    var onCapture: ((UUID) -> Void)?
    @Published private(set) var boards: [ClipboardPinboard] = [] { didSet { revision &+= 1 } }
    @Published private(set) var isLoading = true
    @Published private(set) var canUndoDeletion = false
    @Published private(set) var indexingImages = false
    /// Set while the clipboard shelf is on screen: background results (image
    /// OCR) wait instead of re-rendering the cards under the pointer.
    var defersBackgroundUpdates = false {
        didSet { if !defersBackgroundUpdates { applyPendingTouches(); applyPendingLayouts() } }
    }
    /// "Copied again" timestamps recorded while the shelf is open. Applying
    /// them reorders the history, so it waits until the shelf has closed.
    private var pendingTouches: [UUID: Date] = [:]

    private func applyPendingTouches() {
        guard !pendingTouches.isEmpty else { return }
        let touches = pendingTouches
        pendingTouches.removeAll()
        var updated = entries
        for index in updated.indices { if let date = touches[updated[index].id] { updated[index].lastCopiedAt = date } }
        updated.sort { $0.lastCopiedAt > $1.lastCopiedAt }
        entries = updated
        scheduleSave()
    }
    private var deletionHistory: [DeletionBatch] = []
    private var indexingTask: Task<Void, Never>?
    private var attemptedImages: Set<UUID> = []
    private let indexingQueue = DispatchQueue(label: "com.kyw.allofmacos.clipboard-ocr", qos: .utility)
    @Published var lastError: String?
    /// Whether the archive can currently be read and written. A transient
    /// failure is retried automatically; an unreadable archive waits for the
    /// user, so a failed read never overwrites the only copy of the history.
    @Published private(set) var storageStatus: StorageStatus = .ok
    /// A persistent, user-facing explanation shown while persistence is blocked.
    @Published private(set) var storageWarning: String?
    @Published var paused = false {
        didSet {
            // Pausing is a privacy boundary: resuming must not ingest anything
            // that was copied while collection was suspended.
            captureGeneration += 1
            lastChangeCount = pasteboard.changeCount
            // Every resume path (including keyboard/menu toggles) clears a timed pause.
            if !paused {
                pauseTimer?.invalidate()
                pauseTimer = nil
                pauseRemainingSeconds = 0
            }
        }
    }
    @Published var pauseRemainingSeconds: Int = 0
    private var pauseTimer: Timer?

    func pause(for durationSeconds: Int = 0) {
        paused = true
        pauseTimer?.invalidate()
        if durationSeconds > 0 {
            pauseRemainingSeconds = durationSeconds
            pauseTimer = Timer.scheduledTimer(withTimeInterval: 1.0, repeats: true) { [weak self] timer in
                DispatchQueue.main.async {
                    guard let self else { timer.invalidate(); return }
                    if self.pauseRemainingSeconds > 1 {
                        self.pauseRemainingSeconds -= 1
                    } else {
                        self.resume()
                        timer.invalidate()
                    }
                }
            }
        } else {
            pauseRemainingSeconds = 0
            pauseTimer = nil
        }
    }

    func resume() {
        paused = false
        pauseRemainingSeconds = 0
        pauseTimer?.invalidate()
        pauseTimer = nil
    }
    @Published var settings: Settings {
        didSet {
            guard settings != oldValue else { return }
            captureGeneration += 1
            lastChangeCount = pasteboard.changeCount
            if let data = try? JSONEncoder().encode(settings.bounded) { defaults.set(data, forKey: Self.settingsKey) }
            trim()
            scheduleSave()
        }
    }

