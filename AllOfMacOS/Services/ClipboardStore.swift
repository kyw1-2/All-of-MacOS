    init(directory: URL? = nil, pasteboard: NSPasteboard? = nil, defaults: UserDefaults? = nil,
         now: @escaping () -> Date = Date.init) {
        let isolated = PresetManager.isRunningTests || PresetManager.isUIPreview ||
            ProcessInfo.processInfo.arguments.contains("--aom-ui-preview") ||
            Bundle.main.bundleIdentifier?.hasSuffix(".preview") == true
        let token = UUID().uuidString
        self.isolated = isolated || pasteboard != nil
        self.directory = directory ?? (isolated
            ? FileManager.default.temporaryDirectory.appendingPathComponent("AOMClipboard-\(token)", isDirectory: true)
            : FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
                .appendingPathComponent("AllOfMacOS/Clipboard", isDirectory: true))
        self.pasteboard = pasteboard ?? (isolated ? NSPasteboard(name: .init("AOMClipboard.\(token)")) : .general)
        self.defaults = defaults ?? (isolated ? UserDefaults(suiteName: "AOMClipboard.\(token)")! : .standard)
        self.now = now
        self.lastChangeCount = self.pasteboard.changeCount
        if let data = self.defaults.data(forKey: Self.settingsKey), let settings = try? JSONDecoder().decode(Settings.self, from: data) {
            self.settings = settings.bounded
        } else { self.settings = Settings() }
        loadingTask = Task { [weak self] in await self?.loadFromDisk() }
    }

    deinit { timer?.invalidate(); saveTask?.cancel(); storageRetryTask?.cancel() }

    func ready() async { await loadingTask?.value }

    func start() {
        guard timer == nil else { return }
        // Do not capture the user's pre-existing clipboard merely by opening AOM.
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.075, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.01
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        captureGeneration += 1
        lastChangeCount = pasteboard.changeCount
    }

    /// Isolated stores only (UI preview/tests): seed sample items through the
    /// normal capture path. The system pasteboard is never touched.
    func seedIsolatedPasteboard(sourceName: String, sourceBundleID: String,
                                _ write: (NSPasteboard) -> Void) {
        guard isolated else { return }
        pasteboard.clearContents()
        write(pasteboard)
        poll(sourceName: sourceName, sourceBundleID: sourceBundleID)
    }

    func poll(sourceName: String? = nil, sourceBundleID: String? = nil) {
        let count = pasteboard.changeCount
        guard !isLoading else { return }
        if now().timeIntervalSince(lastTrimDate) >= 60 { trim(); lastTrimDate = now() }
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard settings.enabled, !paused else { return }
        let frontmost = isolated ? nil : NSWorkspace.shared.frontmostApplication
        let bundleID = sourceBundleID ?? frontmost?.bundleIdentifier
        let appName = sourceName ?? frontmost?.localizedName
        guard !settings.excludes(bundleID) else { return }
        let boardName = pasteboard.name
        let read = captureReadOverride
        let capturedAt = now()
        let generation = captureGeneration
        let task = Task { [weak self] in
            guard let self else { return }
            // Decoding and classifying a multi-megabyte text can take longer
            // than hashing it. Keep both off the main actor, not only SHA256.
            let snapshot = await onReadQueue {
                read?(boardName, count) ?? Self.readPasteboard(named: boardName, expectedCount: count)
            }
            guard generation == captureGeneration, settings.enabled, !paused else { return }
            let capturedItems: [[String: Data]]
            switch snapshot {
            case .items(let items): capturedItems = items
            case .tooLarge: lastError = StoreError.tooLarge.localizedDescription; return
            case .unavailable: return
            }
            let (entry, digest) = await onCaptureQueue {
                let entry = ClipboardEntry.captured(items: capturedItems, sourceName: appName,
                                                    sourceBundleID: bundleID, at: capturedAt)
                return (entry, entry.payloadDigest)
            }
            guard generation == captureGeneration, settings.enabled, !paused else { return }
            let capturedID: UUID
            if let index = Self.deduplicationIndex(in: entries, digests: digests, digest: digest, excluding: entry.id) {
                var updated = entries
                var existing = updated.remove(at: index)
                existing.lastCopiedAt = entry.lastCopiedAt
                existing.sourceName = entry.sourceName
                existing.sourceBundleID = entry.sourceBundleID
                updated.insert(existing, at: 0)
                entries = updated
                capturedID = existing.id
            } else {
                capturedID = entry.id
                entries.insert(entry, at: 0)
                digests[entry.id] = digest
            }
            trim()
            scheduleSave()
            if entries.contains(where: { $0.id == capturedID }) { onCapture?(capturedID) }
            scheduleImageIndexing()
        }
        captureTasks.append(task)
        if captureTasks.count > 64 { captureTasks.removeFirst(captureTasks.count - 64) }
    }

    enum PasteboardSnapshot {
        case items([[String: Data]]), tooLarge, unavailable
    }
    /// Deterministic slow-provider seam. Production uses a worker-owned board
    /// connection; no promised representation is requested on the UI thread.
    var captureReadOverride: (@Sendable (NSPasteboard.Name, Int) -> PasteboardSnapshot)?

    nonisolated private static func readPasteboard(named name: NSPasteboard.Name, expectedCount: Int) -> PasteboardSnapshot {
        let board = NSPasteboard(name: name)
        guard board.changeCount == expectedCount,
              let boardItems = board.pasteboardItems, !boardItems.isEmpty, boardItems.count <= 32 else { return .unavailable }
        guard !boardItems.contains(where: { item in item.types.contains { Self.excludedTypes.contains($0.rawValue) } }) else { return .unavailable }
        var items: [[String: Data]] = []
        var total = 0
        for boardItem in boardItems {
            var item: [String: Data] = [:]
            for type in boardItem.types.prefix(64) where Self.supportedTypes.contains(type.rawValue) {
                guard let data = boardItem.data(forType: type) else { continue }
                guard data.count <= Self.maximumEntryBytes - total else { return .tooLarge }
                total += data.count
                item[type.rawValue] = data
            }
            if !item.isEmpty { items.append(item) }
        }
        guard !items.isEmpty, board.changeCount == expectedCount else { return .unavailable }
        return .items(items)
    }

    func filtered(query: String = "", kind: ClipboardEntry.Kind? = nil, source: String? = nil,
                  board: UUID? = nil, since: Date? = nil) -> [ClipboardEntry] {
        if query.isEmpty, kind == nil, source == nil, board == nil, since == nil { return entries }
        let search = ClipboardSearchQuery(query, boards: boards)
        let matched = entries.filter { entry in
            (kind == nil || entry.kind == kind) &&
            (source == nil || entry.sourceBundleID == source || entry.sourceName == source) &&
            (board == nil || entry.pinboardIDs.contains(board!)) &&
            (since == nil || entry.lastCopiedAt >= since!) &&
            search.matches(entry, boards: boards)
        }
        return Self.ordered(matched, board: board, boards: boards)
    }

    /// Creates a local reusable clip without changing the system pasteboard.
    /// Pinboards and history share the same stored entry format.
    @discardableResult
    func createTextItem(_ text: String, rtfData: Data? = nil) -> ClipboardEntry? {
        let cleaned = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleaned.isEmpty, text.utf8.count <= Self.maximumEntryBytes else {
            if text.utf8.count > Self.maximumEntryBytes {
                lastError = StoreError.tooLarge.localizedDescription
            }
            return nil
        }
        let entry = ClipboardEntry.captured(
            items: [Self.textRepresentations(text, rtfData: rtfData)],
            sourceName: "All of MacOS", sourceBundleID: "com.kyw.allofmacos",
            at: now())
        entries.insert(entry, at: 0)
        let task = Task { [weak self] in
            guard let self else { return }
            let digest = await onQueue { entry.payloadDigest }
            if entries.contains(where: { $0.id == entry.id }) {
                digests[entry.id] = digest
            }
        }
        captureTasks.append(task)
        trim()
        scheduleSave()
        return entries.first { $0.id == entry.id }
    }

    @discardableResult
    func createBoard(name: String, color: String = "blue") -> ClipboardPinboard {
        let board = ClipboardPinboard(name: String(name.trimmingCharacters(in: .whitespacesAndNewlines).prefix(100)), color: color)
        guard !board.name.isEmpty, boards.count < 100 else { return board }
        boards.append(board)
        scheduleSave()
        return board
    }

    nonisolated static func ordered(_ entries: [ClipboardEntry], board: UUID?, boards: [ClipboardPinboard]) -> [ClipboardEntry] {
        guard let board, let order = boards.first(where: { $0.id == board })?.itemOrder else { return entries }
        let positions = Dictionary(order.enumerated().map { ($0.element, $0.offset) }, uniquingKeysWith: { first, _ in first })
        return entries.enumerated().sorted {
            let left = positions[$0.element.id] ?? (order.count + $0.offset)
            let right = positions[$1.element.id] ?? (order.count + $1.offset)
            return left < right
        }.map(\.element)
    }

    func moveBoard(_ id: UUID, before target: UUID) {
        guard id != target, let source = boards.firstIndex(where: { $0.id == id }), boards.contains(where: { $0.id == target }) else { return }
        let board = boards.remove(at: source)
        boards.insert(board, at: boards.firstIndex(where: { $0.id == target })!)
        scheduleSave()
    }

    func moveItem(_ id: UUID, before target: UUID, in boardID: UUID) {
        guard id != target, let boardIndex = boards.firstIndex(where: { $0.id == boardID }),
              entries.contains(where: { $0.id == id }), entries.contains(where: { $0.id == target && $0.pinboardIDs.contains(boardID) }) else { return }
        pin(entryID: id, boardID: boardID)
        var order = Self.ordered(entries.filter { $0.pinboardIDs.contains(boardID) }, board: boardID, boards: boards).map(\.id)
        order.removeAll { $0 == id }
        guard let insertion = order.firstIndex(of: target) else { return }
        order.insert(id, at: insertion)
        boards[boardIndex].itemOrder = order
        scheduleSave()
    }

    func renameBoard(id: UUID, name: String) {
        let name = String(name.trimmingCharacters(in: .whitespacesAndNewlines).prefix(100))
        guard !name.isEmpty, let index = boards.firstIndex(where: { $0.id == id }) else { return }
        boards[index].name = name
        scheduleSave()
    }

