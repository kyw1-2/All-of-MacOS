/// Local clipboard history. The pasteboard is sampled only after its change
/// counter advances; persistence and hashing never run on the gesture loop.
@MainActor
final class ClipboardStore: ObservableObject {
    struct Settings: Codable, Equatable {
        var enabled = true
        var pasteDirectly = true
        var plainText = false
        var retentionDays = 30
        var ignoredApps: [String] = ["com.1password.1password", "com.agilebits.onepassword7",
                                     "com.bitwarden.desktop", "com.apple.keychainaccess"]
        var maxEntries = 1_000
        var maxBytes = 200 * 1_024 * 1_024
        /// 3.3.3 options. Optional, so settings saved by older versions still
        /// decode (a missing key must never reset the whole struct).
        var searchAllLists: Bool?
        var singlePinboard: Bool?

        /// Paste: a search from a pinboard looks through every list, not only
        /// the pinboard on screen. Typed `board:` filters still narrow it.
        var searchesAllLists: Bool {
            get { searchAllLists ?? true }
            set { searchAllLists = newValue }
        }
        /// Paste: an item belongs to one pinboard; pinning it elsewhere moves
        /// it. Off keeps AOM's behaviour, where an item can sit on several.
        var onePinboardPerItem: Bool {
            get { singlePinboard ?? false }
            set { singlePinboard = newValue }
        }

        /// The excluded-app list as the privacy gate compares it: trimmed and
        /// case-insensitive (audit PA-01).
        var excludedBundleIDs: Set<String> {
            Set(ignoredApps.map { $0.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() }.filter { !$0.isEmpty })
        }

        /// One test for capture, suggestions, the paste log and MCP.
        func excludes(_ bundleID: String?) -> Bool {
            guard let id = bundleID?.trimmingCharacters(in: .whitespacesAndNewlines).lowercased(), !id.isEmpty else { return false }
            return excludedBundleIDs.contains(id)
        }

        var bounded: Settings {
            var result = self
            // Zero means "Indefinitely" in the settings picker.
            result.retentionDays = min(365, max(0, retentionDays))
            result.maxEntries = min(10_000, max(1, maxEntries))
            result.maxBytes = min(1_024 * 1_024 * 1_024, max(1_024, maxBytes))
            result.ignoredApps = Array(Set(ignoredApps.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
                .filter { !$0.isEmpty })).sorted()
            return result
        }
    }

    enum StoreError: LocalizedError {
        case emptySelection, cannotWrite, tooLarge, storageUnavailable, invalidArchive
        var errorDescription: String? {
            switch self {
            case .emptySelection: return "The selected clipboard items are no longer available."
            case .cannotWrite: return "The clipboard could not be updated. Try again."
            case .tooLarge: return "This clipboard item exceeds the 20 MB limit."
            case .storageUnavailable: return "Clipboard history could not be saved. Check its storage folder."
            case .invalidArchive: return "Clipboard history could not be read. The original file was preserved."
            }
        }
    }

    /// Why persistence is (or is not) currently available.
    enum StorageStatus: Equatable {
        case ok
        /// The archive could not be read for a reason that may clear by itself,
        /// such as a locked login Keychain. Reading is retried automatically;
        /// nothing is written until a read succeeds, so the existing archive is
        /// never overwritten while it is merely unreachable.
        case transientFailure
        /// The archive exists but cannot be decoded. Writing stays blocked so
        /// the unreadable bytes are preserved until the user explicitly
        /// recovers, which archives them under a new name first.
        case unreadableArchive
    }

